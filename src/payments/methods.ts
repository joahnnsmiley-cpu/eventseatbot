/**
 * Какой способ оплаты предлагать первым.
 *
 * Дело не во вкусе, а в комиссии: она разная и платит её организатор.
 * По данным личного кабинета Робокассы на 30 сентября 2026:
 *
 *   СБП             1–2%      (не подключён, ждём поддержку)
 *   Яндекс Пэй      4,30–5,90%
 *   Яндекс Сплит    6,00–7,90%
 *   T-Pay           «комиссия равна банковской карте» — то есть те же 8%
 *   Банковская карта 8%
 *
 * Отсюда и порядок. Отказаться от карты совсем нельзя по закону, но никто не
 * обязывает делать её самой заметной — она остаётся второй кнопкой.
 *
 * Список один на всё приложение: экран билетов и полоска-напоминание должны
 * предлагать одно и то же, иначе выходит, что в одном месте мы бережём деньги,
 * а в другом нет.
 */

/**
 * От дешёвого к дорогому. СБП стоит первым заранее: как только его подключат,
 * он станет основным сам, без правок в коде.
 *
 * T-Pay здесь выше Яндекс Пэя по прямой просьбе — на комиссию это не влияет,
 * она у него как у карты. Если важнее экономия, достаточно поменять эти две
 * строки местами.
 */
export const METHOD_PRIORITY = [
  'SBP',
  'TinkoffPay',
  'YandexPay',
  'YandexPaySplit',
] as const;

const LABELS: Record<string, string> = {
  SBP: 'СБП',
  TinkoffPay: 'T-Pay',
  YandexPay: 'Яндекс Пэй',
  YandexPaySplit: 'Яндекс Сплит',
  BankCard: 'картой',
};

/** Самый выгодный из подключённых способов, если он есть. */
export function preferredMethod(methods: string[]): string | null {
  for (const candidate of METHOD_PRIORITY) {
    if (methods.includes(candidate)) return candidate;
  }
  return null;
}

/** Как способ называется на кнопке. */
export function methodLabel(method: string): string {
  return LABELS[method] ?? method;
}

/**
 * Надпись на основной кнопке.
 *
 * «Оплатить через СБП», но «Оплатить картой» — предлог зависит от слова, и без
 * этого получается «оплатить через картой».
 */
export function payButtonLabel(method: string | null): string {
  if (!method) return 'Оплатить';
  return method === 'BankCard' ? 'Оплатить картой' : `Оплатить через ${methodLabel(method)}`;
}
